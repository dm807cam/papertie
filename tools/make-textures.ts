import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'
import { type RgbaImage, rawSha256, textSha256 } from './src/image'
import { buildTextureSet, TEXTURE_SEED, type TextureEntry } from './src/textures/set'

const OUT_DIR = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'apps',
  'web',
  'public',
  'textures',
)
const LICENCE = 'Generated by tools/make-textures.ts; no third-party sources'

interface ManifestFile {
  path: string
  width: number
  height: number
  rawSha256: string
}

interface Manifest {
  version: 1
  seed: number
  licence: string
  files: ManifestFile[]
}

/** The SVG's units are 128 a side (`deckle.ts`). */
const SVG_BOX = 128

function describe(entry: TextureEntry): ManifestFile {
  if (entry.raster !== undefined) {
    // Drawn by sharp (librsvg), so the record is of its source and scale, not of its pixels.
    const { svg, scale } = entry.raster
    const side = SVG_BOX * scale
    return {
      path: entry.path,
      width: side,
      height: side,
      rawSha256: textSha256(`${scale}x:${svg}`),
    }
  }
  if (entry.svg !== undefined) {
    return { path: entry.path, width: 128, height: 128, rawSha256: textSha256(entry.svg) }
  }
  const img = entry.image as RgbaImage
  return { path: entry.path, width: img.width, height: img.height, rawSha256: rawSha256(img) }
}

function isOpaque(img: RgbaImage): boolean {
  for (let i = 3; i < img.data.length; i += 4) if (img.data[i] !== 255) return false
  return true
}

async function encodeWebp(img: RgbaImage, opts: NonNullable<TextureEntry['webp']>) {
  const raw = Buffer.from(img.data.buffer, img.data.byteOffset, img.data.byteLength)
  let pipeline = sharp(raw, { raw: { width: img.width, height: img.height, channels: 4 } })
  if (isOpaque(img)) pipeline = pipeline.removeAlpha()
  return pipeline
    .webp({ quality: opts.quality, alphaQuality: opts.quality, lossless: opts.lossless ?? false })
    .toBuffer()
}

/** An SVG of the set drawn at `scale` px per unit: a lossless WebP, alpha kept. */
async function rasterWebp({ svg, scale }: NonNullable<TextureEntry['raster']>) {
  return sharp(Buffer.from(svg, 'utf8'), { density: 72 * scale })
    .webp({ lossless: true })
    .toBuffer()
}

async function write(): Promise<void> {
  await mkdir(OUT_DIR, { recursive: true })
  const files: ManifestFile[] = []
  for (const entry of buildTextureSet(TEXTURE_SEED)) {
    const bytes =
      entry.raster !== undefined
        ? await rasterWebp(entry.raster)
        : entry.svg !== undefined
          ? Buffer.from(entry.svg, 'utf8')
          : await encodeWebp(entry.image as RgbaImage, entry.webp ?? { quality: 85 })
    await writeFile(join(OUT_DIR, entry.path), bytes)
    files.push(describe(entry))
    console.log(`${entry.path}  ${(bytes.length / 1024).toFixed(1)} KB`)
  }
  const manifest: Manifest = { version: 1, seed: TEXTURE_SEED, licence: LICENCE, files }
  await writeFile(join(OUT_DIR, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`)
  console.log(`wrote ${files.length} files and manifest.json to ${OUT_DIR}`)
}

/** Regenerates the raw buffers and compares their hashes with the committed manifest. */
async function check(): Promise<boolean> {
  const manifest = JSON.parse(await readFile(join(OUT_DIR, 'manifest.json'), 'utf8')) as Manifest
  const expected = new Map(manifest.files.map((f) => [f.path, f]))
  const problems: string[] = []
  if (manifest.seed !== TEXTURE_SEED) problems.push(`seed ${manifest.seed} != ${TEXTURE_SEED}`)
  for (const entry of buildTextureSet(TEXTURE_SEED)) {
    const want = expected.get(entry.path)
    expected.delete(entry.path)
    const got = describe(entry)
    if (!want) problems.push(`${entry.path}: missing from manifest`)
    else if (want.rawSha256 !== got.rawSha256 || want.width !== got.width) {
      problems.push(`${entry.path}: hash differs`)
    }
    try {
      const onDisk = await readFile(join(OUT_DIR, entry.path))
      if (entry.raster !== undefined || entry.svg === undefined) {
        const meta = await sharp(onDisk).metadata()
        if (meta.width !== got.width || meta.height !== got.height) {
          problems.push(`${entry.path}: file is ${meta.width}x${meta.height}`)
        }
      } else if (onDisk.toString('utf8') !== entry.svg) {
        problems.push(`${entry.path}: file differs from generated svg`)
      }
    } catch {
      problems.push(`${entry.path}: file missing`)
    }
  }
  for (const path of expected.keys()) problems.push(`${path}: in manifest but not generated`)
  for (const p of problems) console.error(p)
  console.log(problems.length ? `${problems.length} problem(s)` : 'textures match the manifest')
  return problems.length === 0
}

if (process.argv.includes('--check')) {
  process.exit((await check()) ? 0 : 1)
} else {
  await write()
}
